#!/usr/bin/env python3
"""Generate shared/lc_tables.h: compact coefficients for the low-CPU modes.

LC_OP_G[fi] is the TPT one-pole gain G = g / (1 + g), g = tan(pi f / fs), in
Q31. It is used by the 1-pole LP/HP and the 4-pole clean cascades.
"""
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = 48000.0


def hz_table():
    text = open(os.path.join(ROOT, 'shared', 'filter_tables.h'), encoding='utf-8').read()
    m = re.search(r'HZ\[128\]\s*=\s*\{(.*?)\};', text, re.S)
    if not m:
        raise SystemExit('HZ[128] not found in shared/filter_tables.h')
    values = [int(x) for x in re.findall(r'\d+', m.group(1))]
    if len(values) != 128:
        raise SystemExit('HZ table has %d entries' % len(values))
    return values


def main():
    hz = hz_table()
    g = [math.tan(math.pi * f / FS) for f in hz]
    op = [int(round((x / (1.0 + x)) * (1 << 31))) for x in g]
    if max(op) >= (1 << 31):
        raise SystemExit('one-pole coefficient overflows Q31')

    out = ['/* generated by tools/gen_lc_tables.py - do not edit',
           ' * TPT one-pole gain G = g/(1+g), g = tan(pi f/fs), Q31. */',
           '#ifndef LC_TABLES_H',
           '#define LC_TABLES_H',
           '',
           'static const int LC_OP_G[128] = {']
    for i in range(0, 128, 8):
        out.append('    ' + ', '.join('%10d' % v for v in op[i:i + 8]) + ',')
    out += ['};', '', '#endif', '']

    dest = os.path.join(ROOT, 'shared', 'lc_tables.h')
    with open(dest, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote %s: G[0]=%d G[64]=%d G[127]=%d' % (dest, op[0], op[64], op[127]))


if __name__ == '__main__':
    main()
